// Generates supabase/migrations/0012_iba_and_collections.sql from
// seed-data/iba-cocktails.json and seed-data/collections.json:
//   - the IBA official cocktails (source = 'iba'), skipping any whose name is
//     already taken (the Difford's rows they overlap with join Classics instead)
//   - the built-in collections (Tiki, Classics, Prohibition) and their members
// Re-run with `node scripts/generate-collections-sql.mjs` after changing the
// seed data; src/lib/collections-seed.test.ts checks the file is up to date.
import fs from "node:fs";

const read = (p) => JSON.parse(fs.readFileSync(new URL(p, import.meta.url), "utf8"));
const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `array[${a.map(q).join(", ")}]::text[]`;
// Same as src/lib/slug.ts. Members are looked up by slug (the stable key).
const slugify = (name) =>
  name
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/['‘’]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
const bySlug = (name) => `(select id from public.cocktails where slug = ${q(slugify(name))})`;

export function buildSql() {
  const iba = read("../seed-data/iba-cocktails.json");
  const { collections } = read("../seed-data/collections.json");
  const out = [];
  out.push("-- GENERATED by scripts/generate-collections-sql.mjs from seed-data/iba-cocktails.json");
  out.push("-- and seed-data/collections.json -- do not edit by hand.");
  out.push(`-- ${iba.cocktails.length} IBA official cocktails (${iba.sourceUrl}, retrieved ${iba.retrieved}),`);
  out.push("-- ingredients as IBA publishes them, methods paraphrased; plus the built-in collections.");
  out.push("");
  out.push(
    "insert into public.cocktails (name, slug, source, source_url, source_note, primary_spirits, glass, garnish, method_summary, ingredients) values"
  );
  out.push(
    iba.cocktails
      .map(
        (c) =>
          `  (${q(c.name)}, ${q(c.slug)}, 'iba', ${q(c.ibaUrl)}, ${q(`IBA official cocktail · ${c.ibaCategoryLabel}`)}, ${arr(c.primarySpirits)}, ${q(c.glass)}, ${q(c.garnish)}, ${q(c.methodSummary)}, ${q(JSON.stringify(c.ingredients))}::jsonb)`
      )
      .join(",\n") + ";"
  );
  out.push("");
  out.push("insert into public.collections (slug, name, description, sort_order, built_in) values");
  out.push(
    collections.map((c) => `  (${q(c.slug)}, ${q(c.name)}, ${q(c.description)}, ${c.sortOrder}, true)`).join(",\n") +
      "\non conflict (slug) do nothing;"
  );
  for (const c of collections) {
    const col = `(select id from public.collections where slug = ${q(c.slug)})`;
    out.push("");
    out.push(`-- ${c.name}`);
    if (c.members === "all-diffords+ours") {
      out.push(
        `insert into public.cocktail_collections (cocktail_id, collection_id)\nselect id, ${col} from public.cocktails where source in ('diffords', 'ours')\non conflict do nothing;`
      );
    }
    const members = [...(Array.isArray(c.members) ? c.members : []), ...(c.extra ?? [])];
    if (members.length > 0) {
      out.push("insert into public.cocktail_collections (cocktail_id, collection_id, note, note_url)");
      out.push(`select m.cocktail_id, ${col}, m.note, m.note_url from (values`);
      out.push(
        members.map((m) => `  (${bySlug(m.name)}, ${q(m.note ?? null)}, ${q(m.noteUrl ?? null)})`).join(",\n")
      );
      // A name that doesn't match fails loudly (cocktail_id is not null).
      out.push(") as m (cocktail_id, note, note_url)\non conflict do nothing;");
    }
  }
  return out.join("\n") + "\n";
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const target = new URL("../supabase/migrations/0012_iba_and_collections.sql", import.meta.url);
  fs.writeFileSync(target, buildSql());
  console.log("wrote supabase/migrations/0012_iba_and_collections.sql");
}
