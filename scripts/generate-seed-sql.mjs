// Generates supabase/seed.sql from seed-data/cocktails.json, so a fresh
// Supabase project can be rebuilt from the repo:
//   1. apply supabase/migrations/0001..NNNN in order
//   2. run supabase/seed.sql            (tasters, 100 cocktails, launch tastings)
//   3. add the taster emails to taster_accounts (see README; kept out of git)
// Re-run with `npm run db:seed-sql` after changing the seed data.
import fs from "node:fs";

const seed = JSON.parse(fs.readFileSync(new URL("../seed-data/cocktails.json", import.meta.url), "utf8"));

// Same as src/lib/slug.ts (its unit tests pin the output for all 100 names).
const slugify = (name) =>
  name
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/['‘’]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `array[${a.map(q).join(", ")}]::text[]`;

const out = [];
out.push("-- GENERATED by scripts/generate-seed-sql.mjs from seed-data/cocktails.json -- do not edit by hand.");
out.push("-- Launch data: tasters, the 100 verified cocktails, and the original tasting log.");
out.push("begin;");
out.push(`insert into public.tasters (initials, display_name) values ('JB', 'John'), ('GM', 'Genny') on conflict (initials) do nothing;`);
out.push("insert into public.cocktails (name, slug, diffords_rank, diffords_guide_id, diffords_guide_url, primary_spirits, glass, garnish, method_summary, ingredients) values");
out.push(
  seed
    .map(
      (c) =>
        `  (${q(c.name)}, ${q(slugify(c.name))}, ${c.diffordsRank}, ${c.diffordsGuideId ?? "null"}, ${q(c.diffordsGuideUrl)}, ${arr(c.primarySpirits ?? [])}, ${q(c.glass)}, ${q(c.garnish)}, ${q(c.methodSummary)}, ${q(JSON.stringify(c.ingredients ?? []))}::jsonb)`
    )
    .join(",\n") + "\non conflict (name) do nothing;"
);
const tastings = [];
for (const c of seed) {
  if (!c.tried) continue;
  for (const [initials, rating, notes] of [["JB", c.jbRating, c.jbNotes], ["GM", c.gmRating, c.gmNotes]]) {
    tastings.push(
      `  ((select id from public.cocktails where name = ${q(c.name)}), (select id from public.tasters where initials = '${initials}'), ${rating ?? "null"}, ${q(notes)}, true)`
    );
  }
}
out.push("insert into public.tastings (cocktail_id, taster_id, rating, notes, tried) values");
out.push(tastings.join(",\n") + "\non conflict (cocktail_id, taster_id) do nothing;");
out.push("commit;");
fs.writeFileSync(new URL("../supabase/seed.sql", import.meta.url), out.join("\n") + "\n");
console.log(`wrote supabase/seed.sql: ${seed.length} cocktails, ${tastings.length} tastings`);
